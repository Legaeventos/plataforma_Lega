create or replace function public.est__checar() returns void language plpgsql as $$
begin
  if not public.est_pode() then raise exception 'Sem permissão: entre na Plataforma Lega com um usuário ativo.'; end if;
end $$;

-- deixa a soma dos lotes igual à quantidade em estoque (mesma regra do controle de bebidas)
create or replace function public.est__lotes_para(p_produto bigint, p_alvo numeric) returns void language plpgsql as $$
declare soma numeric; dif numeric; falta numeric; usar numeric; l record; custo numeric;
begin
  select coalesce(sum(quantidade_disponivel),0) into soma from public.est_lotes where produto_id = p_produto;
  dif := greatest(p_alvo,0) - soma;
  if abs(dif) < 0.0005 then return; end if;
  if dif < 0 then
    falta := -dif;
    for l in select id, quantidade_disponivel from public.est_lotes where produto_id = p_produto and quantidade_disponivel > 0 order by data_compra nulls first, created_at, id loop
      exit when falta <= 0;
      usar := least(l.quantidade_disponivel, falta);
      update public.est_lotes set quantidade_disponivel = quantidade_disponivel - usar, updated_at = now() where id = l.id;
      falta := falta - usar;
    end loop;
  else
    select coalesce(nullif(custo_medio,0), 0) into custo from public.est_estoque where produto_id = p_produto;
    insert into public.est_lotes (produto_id, data_compra, quantidade_original, quantidade_disponivel, custo_unitario, origem)
    values (p_produto, current_date, dif, dif, coalesce(custo,0), 'ajuste');
  end if;
end $$;

-- ---------------------------------------------------------------------
-- COMPRA: cabeçalho + itens + lotes + estoque + movimentação (tudo ou nada)
-- p = {data, fornecedor, observacao, forma_pagamento, plataforma_evento_id,
--      itens:[{produto_id, quantidade_compra, unidade_compra, fator, valor_total, validade}]}
-- ---------------------------------------------------------------------
create or replace function public.est_registrar_compra(p jsonb) returns bigint language plpgsql as $$
declare cid bigint; it jsonb; iid bigint; q numeric; vt numeric; vu numeric; total numeric := 0; e record;
begin
  perform public.est__checar();
  if coalesce(jsonb_array_length(p->'itens'),0) = 0 then raise exception 'A compra precisa de pelo menos um item.'; end if;
  insert into public.est_compras (data, fornecedor, observacao, forma_pagamento, plataforma_evento_id)
  values ((p->>'data')::date, nullif(trim(p->>'fornecedor'),''), nullif(p->>'observacao',''), nullif(p->>'forma_pagamento',''), nullif(p->>'plataforma_evento_id',''))
  returning id into cid;
  for it in select * from jsonb_array_elements(p->'itens') loop
    q  := round(coalesce((it->>'quantidade_compra')::numeric,0) * coalesce(nullif((it->>'fator')::numeric,0),1), 3);
    vt := round(coalesce((it->>'valor_total')::numeric,0), 2);
    if q <= 0 then raise exception 'Quantidade inválida no item da compra.'; end if;
    if not exists (select 1 from public.est_produtos where id = (it->>'produto_id')::bigint) then raise exception 'Produto % não encontrado.', it->>'produto_id'; end if;
    vu := vt / q; total := total + vt;
    insert into public.est_compras_itens (compra_id, produto_id, quantidade, valor_unitario, valor_total, validade, quantidade_compra, unidade_compra)
    values (cid, (it->>'produto_id')::bigint, q, vu, vt, nullif(it->>'validade','')::date, (it->>'quantidade_compra')::numeric, nullif(it->>'unidade_compra',''))
    returning id into iid;
    insert into public.est_lotes (produto_id, compra_id, compra_item_id, data_compra, quantidade_original, quantidade_disponivel, custo_unitario, validade, origem)
    values ((it->>'produto_id')::bigint, cid, iid, (p->>'data')::date, q, q, vu, nullif(it->>'validade','')::date, 'compra');
    insert into public.est_estoque (produto_id) values ((it->>'produto_id')::bigint) on conflict (produto_id) do nothing;
    select * into e from public.est_estoque where produto_id = (it->>'produto_id')::bigint for update;
    update public.est_estoque
       set custo_medio = case when greatest(e.quantidade,0) + q > 0 then (greatest(e.quantidade,0) * e.custo_medio + vt) / (greatest(e.quantidade,0) + q) else vu end,
           quantidade = e.quantidade + q, updated_at = now()
     where produto_id = (it->>'produto_id')::bigint;
    insert into public.est_movimentacoes (produto_id, tipo, quantidade, motivo, data_movimento, referencia_tabela, referencia_id, custo_total)
    values ((it->>'produto_id')::bigint, 'entrada', q, 'Compra' || coalesce(' · ' || nullif(trim(p->>'fornecedor'),''), ''), ((p->>'data')::date + time '12:00')::timestamptz, 'compras', cid, vt);
  end loop;
  update public.est_compras set valor_total = total where id = cid;
  return cid;
end $$;

-- Exclui uma compra cujos itens ainda não foram usados
create or replace function public.est_excluir_compra(p_compra_id bigint) returns void language plpgsql as $$
declare it record; usados int;
begin
  perform public.est__checar();
  select count(*) into usados from public.est_lotes l
   where l.compra_id = p_compra_id and (l.quantidade_disponivel < l.quantidade_original - 0.0005
      or exists (select 1 from public.est_consumos_lotes c where c.lote_id = l.id));
  if usados > 0 then raise exception 'Parte desta compra já foi usada em eventos ou ajustes; para corrigir, faça um ajuste de estoque.'; end if;
  for it in select * from public.est_compras_itens where compra_id = p_compra_id loop
    update public.est_estoque e
       set quantidade = e.quantidade - it.quantidade,
           custo_medio = coalesce((select sum(l.quantidade_disponivel * l.custo_unitario) / nullif(sum(l.quantidade_disponivel),0)
                                     from public.est_lotes l where l.produto_id = it.produto_id and l.compra_item_id is distinct from it.id and l.quantidade_disponivel > 0), e.custo_medio),
           updated_at = now()
     where e.produto_id = it.produto_id;
  end loop;
  delete from public.est_lotes where compra_id = p_compra_id;
  delete from public.est_movimentacoes where referencia_tabela = 'compras' and referencia_id = p_compra_id;
  delete from public.est_compras_itens where compra_id = p_compra_id;
  delete from public.est_compras where id = p_compra_id;
end $$;

-- ---------------------------------------------------------------------
-- CONSUMO DO EVENTO (baixa por lote, do mais antigo para o mais novo)
-- ---------------------------------------------------------------------
create or replace function public.est__desfazer_consumo(p_evento_id bigint) returns void language plpgsql as $$
declare it record;
begin
  for it in select * from public.est_eventos_itens where evento_id = p_evento_id loop
    update public.est_lotes l set quantidade_disponivel = l.quantidade_disponivel + c.quantidade, updated_at = now()
      from public.est_consumos_lotes c where c.evento_item_id = it.id and c.lote_id = l.id;
    update public.est_estoque set quantidade = quantidade + it.quantidade, updated_at = now() where produto_id = it.produto_id;
    delete from public.est_consumos_lotes where evento_item_id = it.id;
  end loop;
  delete from public.est_movimentacoes where referencia_tabela = 'eventos' and referencia_id = p_evento_id;
  delete from public.est_eventos_itens where evento_id = p_evento_id;
end $$;

-- p = {id?, nome_evento, data, adultos, criancas, observacao, tipo_evento, alcoolico_adesao, sem_alcool,
--      rolha_cobrada, valor_rolha, controle_bar, plataforma_evento_id, itens:[{produto_id, quantidade, preco_unitario}]}
create or replace function public.est_registrar_consumo(p jsonb) returns bigint language plpgsql as $$
declare eid bigint; it jsonb; iid bigint; q numeric; falta numeric; usar numeric; custo numeric; cm numeric; l record;
begin
  perform public.est__checar();
  eid := nullif(p->>'id','')::bigint;
  if eid is null and nullif(p->>'plataforma_evento_id','') is not null then
    select id into eid from public.est_eventos where plataforma_evento_id = p->>'plataforma_evento_id';
  end if;
  if eid is not null then
    perform public.est__desfazer_consumo(eid);
    update public.est_eventos set nome_evento = coalesce(nullif(p->>'nome_evento',''), nome_evento), data = coalesce((p->>'data')::date, data),
      adultos = coalesce((p->>'adultos')::int, 0), criancas = coalesce((p->>'criancas')::int, 0), observacao = nullif(p->>'observacao',''),
      tipo_evento = coalesce(nullif(p->>'tipo_evento',''),'fechada'), alcoolico_adesao = coalesce((p->>'alcoolico_adesao')::boolean,false),
      sem_alcool = coalesce((p->>'sem_alcool')::boolean,false), rolha_cobrada = coalesce((p->>'rolha_cobrada')::boolean,false),
      valor_rolha = coalesce((p->>'valor_rolha')::numeric,0), controle_bar = case when jsonb_typeof(p->'controle_bar') = 'object' then p->'controle_bar' end,
      plataforma_evento_id = coalesce(nullif(p->>'plataforma_evento_id',''), plataforma_evento_id),
      receitas = case when jsonb_typeof(p->'receitas') = 'array' and jsonb_array_length(p->'receitas') > 0 then p->'receitas' end
     where id = eid;
    if not found then raise exception 'Consumo de evento % não encontrado.', eid; end if;
  else
    insert into public.est_eventos (nome_evento, data, adultos, criancas, observacao, tipo_evento, alcoolico_adesao, sem_alcool, rolha_cobrada, valor_rolha, controle_bar, plataforma_evento_id, receitas)
    values (coalesce(nullif(p->>'nome_evento',''),'Evento'), (p->>'data')::date, coalesce((p->>'adultos')::int,0), coalesce((p->>'criancas')::int,0), nullif(p->>'observacao',''),
            coalesce(nullif(p->>'tipo_evento',''),'fechada'), coalesce((p->>'alcoolico_adesao')::boolean,false), coalesce((p->>'sem_alcool')::boolean,false),
            coalesce((p->>'rolha_cobrada')::boolean,false), coalesce((p->>'valor_rolha')::numeric,0),
            case when jsonb_typeof(p->'controle_bar') = 'object' then p->'controle_bar' end, nullif(p->>'plataforma_evento_id',''),
            case when jsonb_typeof(p->'receitas') = 'array' and jsonb_array_length(p->'receitas') > 0 then p->'receitas' end)
    returning id into eid;
  end if;

  for it in select * from jsonb_array_elements(coalesce(p->'itens','[]'::jsonb)) loop
    q := round(coalesce((it->>'quantidade')::numeric,0), 3);
    continue when q <= 0;
    insert into public.est_eventos_itens (evento_id, produto_id, quantidade, preco_unitario, valor_total, quantidade_unidades, receita_id)
    values (eid, (it->>'produto_id')::bigint, q, coalesce((it->>'preco_unitario')::numeric,0), round(q * coalesce((it->>'preco_unitario')::numeric,0),2),
            nullif((it->>'unidades')::numeric, 0), nullif(it->>'receita_id','')::bigint)
    returning id into iid;
    falta := q; custo := 0;
    for l in select id, quantidade_disponivel, custo_unitario from public.est_lotes
              where produto_id = (it->>'produto_id')::bigint and quantidade_disponivel > 0
              order by data_compra nulls first, created_at, id for update loop
      exit when falta <= 0;
      usar := least(l.quantidade_disponivel, falta);
      update public.est_lotes set quantidade_disponivel = quantidade_disponivel - usar, updated_at = now() where id = l.id;
      insert into public.est_consumos_lotes (evento_item_id, lote_id, quantidade, custo_unitario) values (iid, l.id, usar, l.custo_unitario);
      custo := custo + usar * l.custo_unitario; falta := falta - usar;
    end loop;
    if falta > 0 then
      select coalesce(custo_medio,0) into cm from public.est_estoque where produto_id = (it->>'produto_id')::bigint;
      custo := custo + falta * coalesce(cm,0);
    end if;
    insert into public.est_estoque (produto_id) values ((it->>'produto_id')::bigint) on conflict (produto_id) do nothing;
    update public.est_estoque set quantidade = quantidade - q, updated_at = now() where produto_id = (it->>'produto_id')::bigint;
    update public.est_eventos_itens set custo_total = round(custo,2) where id = iid;
    insert into public.est_movimentacoes (produto_id, tipo, quantidade, motivo, data_movimento, referencia_tabela, referencia_id, custo_total)
    values ((it->>'produto_id')::bigint, 'saida', q, 'Evento · ' || coalesce(nullif(p->>'nome_evento',''),'Evento'), ((p->>'data')::date + time '12:00')::timestamptz, 'eventos', eid, round(custo,2));
  end loop;
  return eid;
end $$;

create or replace function public.est_excluir_consumo(p_evento_id bigint) returns void language plpgsql as $$
begin
  perform public.est__checar();
  perform public.est__desfazer_consumo(p_evento_id);
  delete from public.est_eventos where id = p_evento_id;
end $$;

-- ---------------------------------------------------------------------
-- AJUSTES: baixa manual (perda, quebra, uso interno) e conferência
-- ---------------------------------------------------------------------
-- p = {produto_id, quantidade (quanto sai), motivo, observacao}
create or replace function public.est_baixa_manual(p jsonb) returns void language plpgsql as $$
declare pid bigint := (p->>'produto_id')::bigint; q numeric := round((p->>'quantidade')::numeric,3); atual numeric; cm numeric;
begin
  perform public.est__checar();
  if q is null or q <= 0 then raise exception 'Informe uma quantidade válida para a baixa.'; end if;
  select quantidade, custo_medio into atual, cm from public.est_estoque where produto_id = pid for update;
  if atual is null then raise exception 'Produto sem estoque.'; end if;
  if atual - q < -0.0005 then raise exception 'A baixa não pode deixar o estoque negativo (há % em estoque).', atual; end if;
  update public.est_estoque set quantidade = atual - q, updated_at = now() where produto_id = pid;
  perform public.est__lotes_para(pid, atual - q);
  insert into public.est_movimentacoes (produto_id, tipo, quantidade, motivo, observacao, custo_total)
  values (pid, 'saida_manual', q, coalesce(nullif(p->>'motivo',''),'Ajuste manual'), nullif(p->>'observacao',''), round(q * coalesce(cm,0),2));
end $$;

-- Conferência (balanço): grava a contagem e acerta o estoque
-- p = {data, observacao, setor, itens:[{produto_id, contada}]}
create or replace function public.est_aplicar_conferencia(p jsonb) returns bigint language plpgsql as $$
declare bid bigint; it jsonb; pid bigint; cont numeric; atual numeric; cm numeric; nome text;
begin
  perform public.est__checar();
  insert into public.est_balancos (data, observacao, setor, aplicado)
  values (coalesce((p->>'data')::date, current_date), nullif(p->>'observacao',''), nullif(p->>'setor',''), true) returning id into bid;
  for it in select * from jsonb_array_elements(coalesce(p->'itens','[]'::jsonb)) loop
    pid := (it->>'produto_id')::bigint; cont := round((it->>'contada')::numeric,3);
    continue when cont is null or cont < 0;
    insert into public.est_estoque (produto_id) values (pid) on conflict (produto_id) do nothing;
    select e.quantidade, e.custo_medio, pr.nome into atual, cm, nome from public.est_estoque e join public.est_produtos pr on pr.id = e.produto_id where e.produto_id = pid for update of e;
    insert into public.est_balancos_itens (balanco_id, produto_id, produto_nome, quantidade_sistema, quantidade_contada, diferenca)
    values (bid, pid, nome, atual, cont, cont - atual);
    if abs(cont - atual) >= 0.0005 then
      update public.est_estoque set quantidade = cont, updated_at = now() where produto_id = pid;
      perform public.est__lotes_para(pid, cont);
      insert into public.est_movimentacoes (produto_id, tipo, quantidade, motivo, observacao, referencia_tabela, referencia_id, custo_total)
      values (pid, case when cont < atual then 'saida_manual' else 'entrada' end, abs(cont - atual), 'Conferência de estoque', nullif(p->>'observacao',''), 'balancos_estoque', bid, round(abs(cont - atual) * coalesce(cm,0),2));
    end if;
  end loop;
  return bid;
end $$;

-- ---------------------------------------------------------------------
-- MIGRAÇÃO do controle de bebidas
-- ---------------------------------------------------------------------
-- Esvazia as tabelas para copiar de novo. Bloqueado depois da virada.
create or replace function public.est_preparar_migracao() returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.est__checar();
  if exists (select 1 from public.est_config where chave = 'virada') then
    raise exception 'A virada já foi feita: o estoque agora é lançado na plataforma e não pode ser copiado de novo do sistema antigo.';
  end if;
  truncate public.est_produtos, public.est_codigos_barras, public.est_estoque, public.est_compras, public.est_compras_itens, public.est_lotes,
           public.est_eventos, public.est_eventos_itens, public.est_consumos_lotes, public.est_movimentacoes, public.est_balancos,
           public.est_balancos_itens, public.est_agenda;
end $$;

-- Acerta os contadores de id depois de copiar com os ids antigos
create or replace function public.est_sincronizar_sequencias() returns void language plpgsql security definer set search_path = public as $$
declare t text; m bigint;
begin
  perform public.est__checar();
  foreach t in array array['est_produtos','est_codigos_barras','est_estoque','est_compras','est_compras_itens','est_lotes','est_eventos',
                           'est_eventos_itens','est_consumos_lotes','est_movimentacoes','est_balancos','est_balancos_itens','est_agenda']
  loop
    execute format('select coalesce(max(id),0) from public.%I', t) into m;
    perform setval(pg_get_serial_sequence('public.' || t, 'id'), greatest(m,1), m > 0);
  end loop;
  -- produto que não tinha linha de estoque ganha uma zerada
  insert into public.est_estoque (produto_id)
  select p.id from public.est_produtos p where not exists (select 1 from public.est_estoque e where e.produto_id = p.id)
  on conflict (produto_id) do nothing;
end $$;

create or replace function public.est_registrar_virada(p jsonb) returns void language plpgsql as $$
begin
  perform public.est__checar();
  insert into public.est_config (chave, valor) values ('virada', p || jsonb_build_object('em', now(), 'por', auth.uid()))
  on conflict (chave) do nothing;
end $$;

