-- Quem pode mexer: usuários ativos da plataforma (tabela lega_perfis)
create or replace function public.est_pode() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.lega_perfis where user_id = auth.uid() and coalesce(ativo, true));
$$;

