-- Segurança: só usuários ativos da plataforma leem e gravam
do $$
declare t text;
begin
  foreach t in array array['est_config','est_receitas','est_produtos','est_codigos_barras','est_estoque','est_compras','est_compras_itens','est_lotes',
                           'est_eventos','est_eventos_itens','est_consumos_lotes','est_movimentacoes','est_balancos','est_balancos_itens','est_agenda']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "lega estoque" on public.%I', t);
    execute format('create policy "lega estoque" on public.%I for all to authenticated using (public.est_pode()) with check (public.est_pode())', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to authenticated;

-- Todo produto novo ganha a linha de estoque
create or replace function public.est_tg_produto_estoque() returns trigger language plpgsql as $$
begin
  -- na migração (linha com legado) o estoque vem copiado do sistema antigo
  if new.legado is null then
    insert into public.est_estoque (produto_id) values (new.id) on conflict (produto_id) do nothing;
  end if;
  return new;
end $$;
drop trigger if exists est_produto_estoque on public.est_produtos;
create trigger est_produto_estoque after insert on public.est_produtos for each row execute function public.est_tg_produto_estoque();

